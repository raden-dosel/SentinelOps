import React, { useState } from 'react';
import { useAuth, RecoveryOptionsSummary } from '../../app/providers/AuthContext';
import {
  Shield,
  Lock,
  User,
  KeyRound,
  AlertCircle,
  HelpCircle,
  Key,
  Server,
  ArrowLeft,
  CheckCircle2,
  Clock,
  Sparkles,
} from 'lucide-react';

export const LoginScreen: React.FC = () => {
  const {
    login,
    getRecoveryOptions,
    resetPasswordWithRecoveryCode,
    resetPasswordWithSecurityAnswer,
    requestServerRecoveryChallenge,
    resetPasswordWithServerAuthorization,
  } = useAuth();

  // Login form state
  const [username, setUsername] = useState('admin');
  const [password, setPassword] = useState('');
  const [error, setError] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const [lockoutSeconds, setLockoutSeconds] = useState<number | null>(null);

  // Recovery flow modal state
  const [showRecovery, setShowRecovery] = useState(false);
  const [recoveryStep, setRecoveryStep] = useState<'identify' | 'select' | 'verify'>('identify');
  const [recoveryUsername, setRecoveryUsername] = useState('admin');
  const [recoveryOptions, setRecoveryOptions] = useState<RecoveryOptionsSummary | null>(null);
  const [selectedMethod, setSelectedMethod] = useState<'code' | 'question' | 'server'>('code');

  // Recovery credentials inputs
  const [recoveryCodeInput, setRecoveryCodeInput] = useState('');
  const [recoveryAnswerInput, setRecoveryAnswerInput] = useState('');
  const [serverAuthCodeInput, setServerAuthCodeInput] = useState('');
  const [serverRequestStatus, setServerRequestStatus] = useState<string | null>(null);

  const [newPassword, setNewPassword] = useState('');
  const [confirmNewPassword, setConfirmNewPassword] = useState('');
  const [recoverySuccessMessage, setRecoverySuccessMessage] = useState('');

  const handleLogin = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');
    setIsLoading(true);

    try {
      const res = await login(username, password);
      if (!res.success) {
        setError(res.error || 'Invalid username or password.');
        if (res.lockoutRemainingSeconds) {
          setLockoutSeconds(res.lockoutRemainingSeconds);
        }
      }
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Login failed.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleStartRecovery = () => {
    setError('');
    setRecoverySuccessMessage('');
    setRecoveryStep('identify');
    setRecoveryUsername(username || 'admin');
    setShowRecovery(true);
  };

  const handleIdentifyAccount = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');
    setIsLoading(true);

    try {
      const options = await getRecoveryOptions(recoveryUsername);
      setRecoveryOptions(options);

      if (options.isLocked && options.lockoutRemainingSeconds) {
        setError(
          `Account recovery is temporarily locked due to repeated failed attempts. Please wait ${options.lockoutRemainingSeconds} seconds.`
        );
        return;
      }

      // Default to the safest available method
      if (options.hasRecoveryCodes) {
        setSelectedMethod('code');
      } else if (options.hasSecurityQuestion) {
        setSelectedMethod('question');
      } else if (options.isEnrolledWithServer) {
        setSelectedMethod('server');
      }

      setRecoveryStep('select');
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Failed to retrieve recovery options.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleRequestServerCode = async () => {
    setError('');
    setServerRequestStatus('Contacting enrolled SentinelOps sync server...');
    setIsLoading(true);

    try {
      const res = await requestServerRecoveryChallenge();
      if (res.success && res.challengeCode) {
        setServerAuthCodeInput(res.challengeCode);
        setServerRequestStatus(
          `Authorization code generated by server: ${res.challengeCode} (Expires: ${new Date(res.expiresAt || '').toLocaleTimeString()})`
        );
      } else {
        setError(res.error || 'Server rejected recovery challenge request.');
        setServerRequestStatus(null);
      }
    } catch {
      setError('Unable to contact sync server. Please verify network connectivity.');
      setServerRequestStatus(null);
    } finally {
      setIsLoading(false);
    }
  };

  const handleRecoverySubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');

    if (newPassword.length < 8) {
      setError('New password must be at least 8 characters long.');
      return;
    }
    if (newPassword !== confirmNewPassword) {
      setError('Passwords do not match.');
      return;
    }

    setIsLoading(true);

    try {
      let result: { success: boolean; error?: string };

      if (selectedMethod === 'code') {
        if (!recoveryCodeInput.trim()) {
          setError('Please enter your emergency recovery code.');
          setIsLoading(false);
          return;
        }
        result = await resetPasswordWithRecoveryCode(
          recoveryUsername,
          recoveryCodeInput.trim(),
          newPassword
        );
      } else if (selectedMethod === 'question') {
        if (!recoveryAnswerInput.trim()) {
          setError('Please provide your security recovery answer.');
          setIsLoading(false);
          return;
        }
        result = await resetPasswordWithSecurityAnswer(
          recoveryUsername,
          recoveryAnswerInput.trim(),
          newPassword
        );
      } else {
        // Server recovery
        if (!serverAuthCodeInput.trim()) {
          setError('Please provide the server emergency authorization code.');
          setIsLoading(false);
          return;
        }
        result = await resetPasswordWithServerAuthorization(
          recoveryUsername,
          serverAuthCodeInput.trim(),
          newPassword
        );
      }

      if (result.success) {
        setRecoverySuccessMessage(
          'Password reset successfully! All other active sessions have been signed out. Please log in with your new password.'
        );
        setShowRecovery(false);
        setPassword('');
        setRecoveryCodeInput('');
        setRecoveryAnswerInput('');
        setServerAuthCodeInput('');
        setNewPassword('');
        setConfirmNewPassword('');
      } else {
        setError(result.error || 'Recovery verification failed.');
      }
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Password reset failed.');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-950 flex items-center justify-center p-4 sm:p-6 text-slate-100">
      <div className="w-full max-w-md rounded-3xl bg-slate-900 border border-slate-800 shadow-2xl p-8 sm:p-10">
        <div className="flex flex-col items-center text-center mb-8">
          <div className="w-16 h-16 rounded-2xl bg-gradient-to-tr from-blue-600 to-indigo-500 flex items-center justify-center shadow-lg shadow-blue-500/20 mb-4">
            <Shield className="w-8 h-8 text-white" />
          </div>
          <h1 className="text-2xl font-black tracking-tight text-white">SentinelOps</h1>
          <p className="text-xs uppercase tracking-widest text-blue-400 font-semibold mt-1">
            Security Operations Vault
          </p>
        </div>

        {error && (
          <div className="mb-6 p-3.5 rounded-xl bg-rose-500/10 border border-rose-500/30 text-rose-300 text-xs font-medium flex items-center gap-2">
            <AlertCircle className="w-4 h-4 shrink-0 text-rose-400" />
            <span>{error}</span>
          </div>
        )}

        {lockoutSeconds && lockoutSeconds > 0 && (
          <div className="mb-6 p-3.5 rounded-xl bg-amber-500/10 border border-amber-500/30 text-amber-300 text-xs font-medium flex items-center gap-2">
            <Clock className="w-4 h-4 shrink-0 text-amber-400" />
            <span>Rate limiting in effect. Please wait before attempting again.</span>
          </div>
        )}

        {recoverySuccessMessage && (
          <div className="mb-6 p-3.5 rounded-xl bg-emerald-500/10 border border-emerald-500/30 text-emerald-300 text-xs font-medium flex items-start gap-2">
            <CheckCircle2 className="w-4 h-4 shrink-0 text-emerald-400 mt-0.5" />
            <span>{recoverySuccessMessage}</span>
          </div>
        )}

        {!showRecovery ? (
          <form onSubmit={handleLogin} className="space-y-4">
            <div>
              <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                Username
              </label>
              <div className="relative">
                <User className="w-4 h-4 text-slate-500 absolute left-3.5 top-1/2 -translate-y-1/2" />
                <input
                  type="text"
                  required
                  value={username}
                  onChange={(e) => setUsername(e.target.value)}
                  placeholder="admin"
                  className="w-full pl-10 pr-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white focus:outline-none focus:border-blue-500"
                />
              </div>
            </div>

            <div>
              <div className="flex items-center justify-between mb-1.5">
                <label className="block text-xs font-semibold text-slate-300">
                  Password
                </label>
                <button
                  type="button"
                  onClick={handleStartRecovery}
                  className="text-[11px] text-blue-400 hover:text-blue-300 transition"
                >
                  Forgot password?
                </button>
              </div>
              <div className="relative">
                <Lock className="w-4 h-4 text-slate-500 absolute left-3.5 top-1/2 -translate-y-1/2" />
                <input
                  type="password"
                  required
                  value={password}
                  onChange={(e) => setPassword(e.target.value)}
                  placeholder="••••••••"
                  className="w-full pl-10 pr-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white focus:outline-none focus:border-blue-500"
                />
              </div>
            </div>

            <button
              type="submit"
              disabled={isLoading}
              className="w-full py-3.5 rounded-xl bg-blue-600 hover:bg-blue-500 active:scale-98 font-bold text-sm text-white shadow-xl shadow-blue-600/30 transition disabled:opacity-50 mt-4 flex items-center justify-center gap-2"
            >
              <KeyRound className="w-4 h-4" />
              <span>{isLoading ? 'Verifying...' : 'Unlock Vault'}</span>
            </button>
          </form>
        ) : (
          <div className="space-y-4">
            <div className="flex items-center justify-between border-b border-slate-800 pb-3">
              <h2 className="text-sm font-bold text-white flex items-center gap-2">
                <KeyRound className="w-4 h-4 text-blue-400" />
                <span>Account Recovery</span>
              </h2>
              <button
                type="button"
                onClick={() => setShowRecovery(false)}
                className="text-xs text-slate-400 hover:text-white"
              >
                Back to Login
              </button>
            </div>

            {recoveryStep === 'identify' && (
              <form onSubmit={handleIdentifyAccount} className="space-y-4">
                <p className="text-xs text-slate-400">
                  Enter your local username to view available verified recovery methods.
                </p>

                <div>
                  <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                    Account Username
                  </label>
                  <div className="relative">
                    <User className="w-4 h-4 text-slate-500 absolute left-3.5 top-1/2 -translate-y-1/2" />
                    <input
                      type="text"
                      required
                      value={recoveryUsername}
                      onChange={(e) => setRecoveryUsername(e.target.value)}
                      placeholder="admin"
                      className="w-full pl-10 pr-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white focus:outline-none focus:border-blue-500"
                    />
                  </div>
                </div>

                <div className="flex items-center gap-2 pt-2">
                  <button
                    type="button"
                    onClick={() => setShowRecovery(false)}
                    className="w-1/2 py-2.5 rounded-xl bg-slate-800 text-xs font-semibold text-slate-300 hover:bg-slate-700"
                  >
                    Cancel
                  </button>
                  <button
                    type="submit"
                    disabled={isLoading}
                    className="w-1/2 py-2.5 rounded-xl bg-blue-600 text-xs font-semibold text-white hover:bg-blue-500 disabled:opacity-50"
                  >
                    {isLoading ? 'Checking...' : 'Continue'}
                  </button>
                </div>
              </form>
            )}

            {recoveryStep === 'select' && recoveryOptions && (
              <div className="space-y-4">
                <p className="text-xs text-slate-300">
                  Choose an authorized recovery factor for <strong>{recoveryUsername}</strong>:
                </p>

                <div className="space-y-2">
                  {recoveryOptions.hasRecoveryCodes && (
                    <button
                      type="button"
                      onClick={() => {
                        setSelectedMethod('code');
                        setRecoveryStep('verify');
                      }}
                      className={`w-full text-left p-3.5 rounded-xl border transition flex items-start gap-3 ${
                        selectedMethod === 'code'
                          ? 'bg-blue-600/10 border-blue-500/50 text-white'
                          : 'bg-slate-800/60 border-slate-700/60 text-slate-300 hover:bg-slate-800'
                      }`}
                    >
                      <Key className="w-4 h-4 text-blue-400 mt-0.5 shrink-0" />
                      <div className="flex-1">
                        <div className="flex items-center justify-between">
                          <span className="text-xs font-bold text-white">One-Time Recovery Code</span>
                          <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-blue-500/20 text-blue-300">
                            Recommended
                          </span>
                        </div>
                        <p className="text-[11px] text-slate-400 mt-0.5">
                          Use one of your 8 emergency codes saved during vault setup ({recoveryOptions.remainingRecoveryCodesCount} remaining).
                        </p>
                      </div>
                    </button>
                  )}

                  {recoveryOptions.hasSecurityQuestion && (
                    <button
                      type="button"
                      onClick={() => {
                        setSelectedMethod('question');
                        setRecoveryStep('verify');
                      }}
                      className={`w-full text-left p-3.5 rounded-xl border transition flex items-start gap-3 ${
                        selectedMethod === 'question'
                          ? 'bg-blue-600/10 border-blue-500/50 text-white'
                          : 'bg-slate-800/60 border-slate-700/60 text-slate-300 hover:bg-slate-800'
                      }`}
                    >
                      <HelpCircle className="w-4 h-4 text-indigo-400 mt-0.5 shrink-0" />
                      <div className="flex-1">
                        <span className="text-xs font-bold text-white">Security Question</span>
                        <p className="text-[11px] text-slate-400 mt-0.5">
                          Answer the security question established during initial vault setup.
                        </p>
                      </div>
                    </button>
                  )}

                  {recoveryOptions.isEnrolledWithServer && (
                    <button
                      type="button"
                      onClick={() => {
                        setSelectedMethod('server');
                        setRecoveryStep('verify');
                      }}
                      className={`w-full text-left p-3.5 rounded-xl border transition flex items-start gap-3 ${
                        selectedMethod === 'server'
                          ? 'bg-blue-600/10 border-blue-500/50 text-white'
                          : 'bg-slate-800/60 border-slate-700/60 text-slate-300 hover:bg-slate-800'
                      }`}
                    >
                      <Server className="w-4 h-4 text-emerald-400 mt-0.5 shrink-0" />
                      <div className="flex-1">
                        <span className="text-xs font-bold text-white">Server Emergency Recovery</span>
                        <p className="text-[11px] text-slate-400 mt-0.5">
                          Use an authorization code issued by your enrolled sync server or operations administrator.
                        </p>
                      </div>
                    </button>
                  )}
                </div>

                <div className="flex items-center gap-2 pt-2">
                  <button
                    type="button"
                    onClick={() => setRecoveryStep('identify')}
                    className="w-full py-2 rounded-xl bg-slate-800 text-xs font-semibold text-slate-300 hover:bg-slate-700 flex items-center justify-center gap-1.5"
                  >
                    <ArrowLeft className="w-3.5 h-3.5" />
                    <span>Change Account</span>
                  </button>
                </div>
              </div>
            )}

            {recoveryStep === 'verify' && (
              <form onSubmit={handleRecoverySubmit} className="space-y-4">
                {selectedMethod === 'code' && (
                  <div>
                    <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                      Emergency Recovery Code
                    </label>
                    <div className="relative">
                      <Key className="w-4 h-4 text-slate-500 absolute left-3.5 top-1/2 -translate-y-1/2" />
                      <input
                        type="text"
                        required
                        value={recoveryCodeInput}
                        onChange={(e) => setRecoveryCodeInput(e.target.value)}
                        placeholder="REC-XXXX-XXXX"
                        className="w-full pl-10 pr-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white font-mono placeholder-slate-500 focus:outline-none focus:border-blue-500 uppercase"
                      />
                    </div>
                    <p className="text-[11px] text-slate-400 mt-1">
                      Enter any one of your 8 single-use codes (dashes are optional).
                    </p>
                  </div>
                )}

                {selectedMethod === 'question' && (
                  <div>
                    <div className="p-3 rounded-xl bg-slate-800/60 border border-slate-700/60 text-xs text-slate-300 mb-2">
                      <span className="font-semibold text-blue-300">Question: </span>
                      {recoveryOptions?.securityQuestion || 'Your security recovery question'}
                    </div>
                    <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                      Security Answer
                    </label>
                    <div className="relative">
                      <HelpCircle className="w-4 h-4 text-slate-500 absolute left-3.5 top-1/2 -translate-y-1/2" />
                      <input
                        type="text"
                        required
                        value={recoveryAnswerInput}
                        onChange={(e) => setRecoveryAnswerInput(e.target.value)}
                        placeholder="Your secret answer"
                        className="w-full pl-10 pr-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white placeholder-slate-500 focus:outline-none focus:border-blue-500"
                      />
                    </div>
                  </div>
                )}

                {selectedMethod === 'server' && (
                  <div className="space-y-3">
                    <div className="p-3 rounded-xl bg-slate-800/60 border border-slate-700/60 text-xs text-slate-300 space-y-2">
                      <p>
                        This tablet is enrolled with your cloud sync server. An authorized server challenge can verify your device identity.
                      </p>
                      <button
                        type="button"
                        onClick={handleRequestServerCode}
                        disabled={isLoading}
                        className="py-1.5 px-3 rounded-lg bg-emerald-600/30 hover:bg-emerald-600/40 border border-emerald-500/40 text-[11px] font-bold text-emerald-300 transition flex items-center gap-1.5"
                      >
                        <Sparkles className="w-3.5 h-3.5" />
                        <span>Request Server Authorization Challenge</span>
                      </button>
                      {serverRequestStatus && (
                        <p className="text-[11px] text-emerald-400 font-mono break-all">
                          {serverRequestStatus}
                        </p>
                      )}
                    </div>

                    <div>
                      <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                        Server Authorization Code
                      </label>
                      <input
                        type="text"
                        required
                        value={serverAuthCodeInput}
                        onChange={(e) => setServerAuthCodeInput(e.target.value)}
                        placeholder="REC-XXXX-XXXX"
                        className="w-full px-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white font-mono placeholder-slate-500 focus:outline-none focus:border-blue-500 uppercase"
                      />
                    </div>
                  </div>
                )}

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-2 border-t border-slate-800">
                  <div>
                    <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                      New Master Password
                    </label>
                    <input
                      type="password"
                      required
                      value={newPassword}
                      onChange={(e) => setNewPassword(e.target.value)}
                      placeholder="Min 8 characters"
                      className="w-full px-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white placeholder-slate-500 focus:outline-none focus:border-blue-500"
                    />
                  </div>

                  <div>
                    <label className="block text-xs font-semibold text-slate-300 mb-1.5">
                      Confirm Password
                    </label>
                    <input
                      type="password"
                      required
                      value={confirmNewPassword}
                      onChange={(e) => setConfirmNewPassword(e.target.value)}
                      placeholder="••••••••"
                      className="w-full px-4 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-sm text-white placeholder-slate-500 focus:outline-none focus:border-blue-500"
                    />
                  </div>
                </div>

                <div className="flex items-center gap-2 pt-2">
                  <button
                    type="button"
                    onClick={() => setRecoveryStep('select')}
                    className="w-1/3 py-2.5 rounded-xl bg-slate-800 text-xs font-semibold text-slate-300 hover:bg-slate-700"
                  >
                    Back
                  </button>
                  <button
                    type="submit"
                    disabled={isLoading}
                    className="w-2/3 py-2.5 rounded-xl bg-blue-600 text-xs font-semibold text-white hover:bg-blue-500 disabled:opacity-50"
                  >
                    {isLoading ? 'Resetting...' : 'Reset Password'}
                  </button>
                </div>
              </form>
            )}
          </div>
        )}
      </div>
    </div>
  );
};
